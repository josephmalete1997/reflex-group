// Helper function to find plan by ID
function getPlanById($plans, $id) {
    foreach ($plans as $plan) {
        if ($plan['id'] === $id) {
            return $plan;
        }
    }
    return null;
}

// Helper function to get related plans
function getRelatedPlans($plans, $currentId, $limit = 4) {
    $related = [];
    foreach ($plans as $plan) {
        if ($plan['id'] !== $currentId && count($related) < $limit) {
            $related[] = $plan;
        }
    }
    return $related;
}
